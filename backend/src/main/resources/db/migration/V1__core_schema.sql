-- Schema "core" canonico (PostgreSQL). Porte de scripts/migration/001_create_core_schema.sql.
-- Convencoes: ids BIGINT IDENTITY (BY DEFAULT permite preservar ids legados no ETL),
-- timestamps TIMESTAMPTZ default now(), flags BOOLEAN, soft-delete via deleted_at.

CREATE TABLE ops_migration_runs (
  id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  migration_key VARCHAR(120) NOT NULL,
  started_at    TIMESTAMPTZ NOT NULL DEFAULT now(),
  finished_at   TIMESTAMPTZ NULL,
  run_status    VARCHAR(20) NOT NULL,
  details       TEXT NULL
);
CREATE INDEX idx_ops_migration_runs_started_at ON ops_migration_runs (started_at);
CREATE INDEX idx_ops_migration_runs_status ON ops_migration_runs (run_status);

CREATE TABLE app_admin_users (
  id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  legacy_admin_id    BIGINT NULL,
  username           VARCHAR(120) NOT NULL,
  password_hash      VARCHAR(255) NOT NULL,
  password_algorithm VARCHAR(20) NOT NULL DEFAULT 'MD5',
  is_active          BOOLEAN NOT NULL DEFAULT TRUE,
  created_by         BIGINT NULL,
  created_at         TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_by         BIGINT NULL,
  updated_at         TIMESTAMPTZ NOT NULL DEFAULT now(),
  deleted_by         BIGINT NULL,
  deleted_at         TIMESTAMPTZ NULL,
  CONSTRAINT uk_app_admin_users_username UNIQUE (username),
  CONSTRAINT uk_app_admin_users_legacy_admin_id UNIQUE (legacy_admin_id)
);
CREATE INDEX idx_app_admin_users_deleted_at ON app_admin_users (deleted_at);

CREATE TABLE app_users (
  id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  legacy_user_id BIGINT NULL,
  display_name   VARCHAR(150) NOT NULL,
  email          VARCHAR(190) NOT NULL,
  phone          VARCHAR(40) NULL,
  password_hash  VARCHAR(255) NULL,
  user_type      VARCHAR(30) NOT NULL DEFAULT 'Normal',
  is_active      BOOLEAN NOT NULL DEFAULT TRUE,
  avatar_ref     VARCHAR(255) NULL,
  acervo_id      BIGINT NULL,
  created_by     BIGINT NULL,
  created_at     TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_by     BIGINT NULL,
  updated_at     TIMESTAMPTZ NOT NULL DEFAULT now(),
  deleted_by     BIGINT NULL,
  deleted_at     TIMESTAMPTZ NULL,
  CONSTRAINT uk_app_users_email UNIQUE (email),
  CONSTRAINT uk_app_users_legacy_user_id UNIQUE (legacy_user_id)
);
CREATE INDEX idx_app_users_is_active ON app_users (is_active);
CREATE INDEX idx_app_users_acervo_id ON app_users (acervo_id);
CREATE INDEX idx_app_users_deleted_at ON app_users (deleted_at);

CREATE TABLE app_user_identities (
  id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id          BIGINT NOT NULL,
  provider         VARCHAR(30) NOT NULL,
  provider_user_id VARCHAR(190) NOT NULL,
  created_by       BIGINT NULL,
  created_at       TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_by       BIGINT NULL,
  updated_at       TIMESTAMPTZ NOT NULL DEFAULT now(),
  deleted_by       BIGINT NULL,
  deleted_at       TIMESTAMPTZ NULL,
  CONSTRAINT uk_app_user_identities_provider_uid UNIQUE (provider, provider_user_id),
  CONSTRAINT fk_app_user_identities_user FOREIGN KEY (user_id) REFERENCES app_users (id) ON DELETE CASCADE
);
CREATE INDEX idx_app_user_identities_user ON app_user_identities (user_id);
CREATE INDEX idx_app_user_identities_deleted_at ON app_user_identities (deleted_at);

